#!/usr/bin/env python3
"""
Regenerates kernel/swissvideo/Patch_Video.inc from Swiss's patcher.c.

The goal is to keep the ported code as close to upstream Swiss as possible,
so future Swiss fixes can be pulled in by re-running this script:

    python3 port_patch_video.py /path/to/swiss-gc/cube/swiss/source/patcher.c \
        Patch_Video.inc video_tables.inc Patch_Extras.inc

Patch_Extras.inc gets Patch_Widescreen() (Force Widescreen) and
Patch_TexFilt() (Force Anisotropic Filter).

Only mechanical edits are made (see EDITS below); everything else is
copied verbatim.
"""
import re
import sys

src_path = sys.argv[1]
out_inc = sys.argv[2] if len(sys.argv) > 2 else 'Patch_Video.inc'
out_tables = sys.argv[3] if len(sys.argv) > 3 else 'video_tables.inc'
out_extras = sys.argv[4] if len(sys.argv) > 4 else 'Patch_Extras.inc'

src = open(src_path).read().split('\n')


def find_line(pred, start=0):
    for n in range(start, len(src)):
        if pred(src[n]):
            return n
    raise SystemExit('pattern not found')


# --- Patch_Video() body -----------------------------------------------------
start = find_line(lambda l: l.startswith('void Patch_Video(u32 *data, u32 length, int dataType)'))
end = find_line(lambda l: l == '}', start)
func = src[start:end + 1]

# --- timing / filter tables that precede it ---------------------------------
tstart = find_line(lambda l: l.startswith('u8 video_timing[] = {'))
tables = src[tstart:start]
tables = [l for l in tables if not l.startswith('extern GXRModeObj *newmode')]
tables = ['static ' + l if re.match(r'^u8 \w+\[', l) else l for l in tables]

out = []
sigs = []  # (name, is_array)
for l in func:
    # 1. Signature tables become static: Swiss keeps ~250 of them on the stack,
    #    which would overflow the kernel stack. They are reset on every call.
    m = re.match(r'^(\t)FuncPattern (\w+)(\[\d+\])?\s*=\s*(\{)?\s*$', l)
    if m:
        sigs.append((m.group(2), bool(m.group(3))))
        l = m.group(1) + 'static ' + l.lstrip('\t')
    # 2. Reset the static tables right before the scan starts.
    if l.strip() == '_SDA2_BASE_ = _SDA_BASE_ = 0;':
        for name, is_array in sigs:
            if is_array:
                out.append('\tswv_reset_sigs(%s, countof(%s));' % (name, name))
            else:
                out.append('\tswv_reset_sigs(&%s, 1);' % name)
        out.append('\tswv_reset_patch_locations();')
        out.append('\t')
    # 3. Low memory variables are written through accessors (ARM side).
    l = re.sub(r'memcpy\(VAR_VFILTER, ', 'var_memcpy(VAR_VFILTER, ', l)
    l = re.sub(r'\*\(u8 \*\)(VAR_\w+) = (.*);', r'var_write8(\1, \2);', l)
    l = re.sub(r'\*\(u16 \*\)(VAR_\w+) = (.*);', r'var_write16(\1, \2);', l)
    l = l.replace('(u32)(VAR_CURRENT_FIELD - VAR_AREA + 0x80000000)',
                  '(u32)(VAR_AREA_ADDR + VAR_CURRENT_FIELD)')
    # 4. Writes into an installed hook go through its physical address.
    l = re.sub(r'^(\s*)(\w+Hook\w*)\[ *(\d+)\] = ', r'\1P2C_PTR(\2)[\3] = ', l)
    # 5. Debug output uses the kernel logger.
    l = l.replace('print_debug(', 'dbgprintf(')
    out.append(l)

out[0] = 'static void Patch_Video(u32 *data, u32 length, int dataType)'


# --- Patch_Widescreen() / Patch_TexFilt() ------------------------------------
def port_extra(proto):
    start = find_line(lambda l: l.startswith(proto))
    end = find_line(lambda l: l == '}', start)
    body = src[start:end + 1]
    res, names, reset_done = [], [], False
    for l in body:
        m = re.match(r'^(\t)FuncPattern (\w+)(\[\d+\])?\s*=\s*(\{)?\s*$', l)
        if m:
            names.append((m.group(2), bool(m.group(3))))
            l = m.group(1) + 'static ' + l.lstrip('\t')
        # reset the static tables before the first scan loop
        if not reset_done and names and l.startswith('\tfor (i = 0;'):
            for name, is_array in names:
                if is_array:
                    res.append('\tswv_reset_sigs(%s, countof(%s));' % (name, name))
                else:
                    res.append('\tswv_reset_sigs(&%s, 1);' % name)
            res.append('\t')
            reset_done = True
        l = re.sub(r'\*\(u32 ?\*\)(VAR_\w+) = (.*);', r'var_write32(\1, \2);', l)
        l = re.sub(r'^(\s*)(\w+Hook\w*)\[ *(\d+)\] = ', r'\1P2C_PTR(\2)[\3] = ', l)
        l = l.replace('print_debug(', 'dbgprintf(')
        res.append(l)
    res[0] = 'static ' + res[0]
    return res

extras = []
for proto in ('void Patch_Widescreen(u32 *data, u32 length, int dataType)',
              'int Patch_TexFilt(u32 *data, u32 length, int dataType)'):
    extras += port_extra(proto) + ['']

hdr = ['/* AUTO-GENERATED by port_patch_video.py from Swiss patcher.c - do not edit */', '']
open(out_inc, 'w').write('\n'.join(hdr + out) + '\n')
open(out_tables, 'w').write('\n'.join(hdr + tables) + '\n')
open(out_extras, 'w').write('\n'.join(hdr + extras))
print('ported %d lines, %d signature tables' % (len(out), len(sigs)))
